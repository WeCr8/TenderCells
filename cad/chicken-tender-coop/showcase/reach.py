"""Reach + clearance tables for the three robot options -> reports/CT_COOP_A_showcase_reach.json/.md"""
from __future__ import annotations
import json, math, os, sys, time
import numpy as np
import sc_params as P, so101, arm
from sc_model import egg_positions

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REACH_TOL = 2.0     # mm: IK residual that still counts as reached


def so101_option(cfg):
    rows = []
    for e in egg_positions():
        x, y, z = e["pos"]
        base = arm.plus_base() if cfg == "plus" else arm.pro_base(arm.pro_carriage_for_egg(y))
        r = {"egg": e["id"]}
        for nm, tgt in (("approach", (x, y, z + 100)), ("grasp", (x, y, z + arm.GRASP_DZ))):
            q, err, tilt = so101.ik_fast(tgt, base, cone_deg=35)
            pts = arm.arm_points(q, base)
            cl = arm.clearance(pts, cfg, skip=("nest floor + liner",) if nm == "grasp" else ())
            r[nm] = {"err_mm": round(err, 1), "tilt_deg": round(tilt, 1),
                     "min_clear_mm": round(min(cl.values()), 1), "worst": min(cl, key=cl.get),
                     "liner_clear_mm": round(arm.clearance(pts, cfg)["nest floor + liner"], 1),
                     "q_deg": {k: round(math.degrees(v), 1) for k, v in q.items() if k != "gripper"}}
        r["reached"] = bool(r["approach"]["err_mm"] < REACH_TOL and r["grasp"]["err_mm"] < REACH_TOL)
        rows.append(r)
    return rows


def so101_traj(cfg):
    egg = [e for e in egg_positions() if e["id"] == arm.PICK][0]["pos"]
    traj = arm.solve_traj(cfg, egg)
    wp = [{"name": n, "err_mm": round(e, 1), "tilt_deg": round(t, 1)} for n, q, b, e, t in traj if not n.startswith("to ")]
    worst_err = max(e for n, q, b, e, t in traj)
    worst = {}
    for seg, s, q, B in arm.interp_path(traj, n=3):
        pts = arm.arm_points(q, B)
        held = seg in ("lift", "to lift", "cross rim", "to cross rim", "over basket", "to over basket", "to release")
        if held:
            pts = np.concatenate([pts, arm.egg_held_points(q, B)])
        skip = ("nest floor + liner",) if seg in ("grasp", "to grasp", "to lift") else ()
        if "release" in seg:
            skip = skip + ("basket rim",)
        for k, v in arm.clearance(pts, cfg, skip=skip).items():
            if k not in worst or v < worst[k][0]:
                worst[k] = (round(v, 1), seg)
    return {"waypoints": wp, "max_ik_err_dense_mm": round(worst_err, 1), "min_clearance_mm_by_obstacle": {k: {"mm": v[0], "where": v[1]} for k, v in worst.items()},
            "traj_deg": [{"name": n, "q": {k: round(math.degrees(v), 2) for k, v in q.items()},
                          "base_mm": [round(float(c) * 1000, 1) for c in b[:3, 3]]} for n, q, b, e, t in traj]}


def starter_option():
    """2-axis Y/Z rail over the box centre line: geometric check, cup Ø20 on a Ø24 plunger."""
    rows = []
    for e in egg_positions():
        x, y, z = e["pos"]
        lateral = abs(x - P.ST_RAIL_X)
        y_ok = P.ST_RAIL_Y[0] + 35 <= y <= P.ST_RAIL_Y[1] - 35
        cup_tol = 6.0       # ASSUMED lateral miss a 20 mm bellows cup on a Ø45 shell still seals
        rows.append({"egg": e["id"], "lateral_offset_mm": round(lateral, 1), "y_in_travel": bool(y_ok),
                     "reached_flat_pad": bool(y_ok and lateral <= cup_tol),
                     "reached_with_centering_pad": bool(y_ok)})
    plunger_r = 12.0
    wall = P.ST_RAIL_X - plunger_r - (P.COOP_W + P.PLY_WALL)
    outer = (P.NB_X1 - P.NB_T) - (P.ST_RAIL_X + plunger_r)
    return {"rows": rows,
            "clearances_mm": {"plunger to coop right wall": round(wall, 1), "plunger to nest outer rim": round(outer, 1),
                              "held egg bottom over the 6 in divider rim (cup at z 1040)": round(1040 - P.EGG_D - (P.NEST_FLOOR_Z + P.RIM_ROBOT), 1),
                              "held egg bottom over the back-end rim (cup at z 1040)": round(1040 - P.EGG_D - (P.NEST_FLOOR_Z + P.RIM_ROBOT), 1),
                              "roost (inside the coop, behind the wall)": round(P.ST_RAIL_X - (P.COOP_W / 2 + P.ROOST_L / 2), 1)},
            "z_stroke_mm": round(1065 - (P.EGG_Z + P.EGG_D / 2), 1), "y_travel_mm": round(P.ST_RAIL_Y[1] - P.ST_RAIL_Y[0], 1)}


def md(rep):
    L = ["# Chicken Tender showcase - reach + clearance (generated by showcase/reach.py)", ""]
    L.append("Egg grid: 3x3 per box at -80/0/+80 mm about each box centre (18 positions), eggs Ø45 x 57 lying on a 12 mm pad. "
             "SO-101 reach = IK on the public URDF to the gripper frame with the approach within 35 deg of vertical; "
             "clearance = closest SO-101 mesh vertex (decimated URDF STLs) to each obstacle box. ASSUMED egg spread.")
    for cfg in ("plus", "pro"):
        o = rep.get(cfg, {})
        if "eggs" not in o:
            continue
        n = sum(r["reached"] for r in o["eggs"])
        L += ["", f"## {cfg.title()} - SO-101 {'inverted under the hood' if cfg == 'plus' else 'inverted on a Y gantry'}: {n}/18 egg positions reached", "",
              "| egg | grasp err mm | tilt deg | min clearance mm (grasp) | worst obstacle | liner clearance mm | approach min clearance mm |", "|---|---:|---:|---:|---|---:|---:|"]
        for r in o["eggs"]:
            g, a = r["grasp"], r["approach"]
            L.append(f"| {r['egg']} | {g['err_mm']} | {g['tilt_deg']} | {g['min_clear_mm']} | {g['worst']} | {g['liner_clear_mm']} | {a['min_clear_mm']} |")
        tr = o.get("traj")
        if not tr:
            L += ["", f"Pick-and-place sweep: not computed yet (run `python reach.py {cfg}_traj md`)."]
            continue
        L += ["", f"Pick-and-place sweep for egg {arm.PICK} (joint-space interpolation, egg in the gripper while carried):", "",
              "| obstacle | min clearance mm | where |", "|---|---:|---|"]
        for k, v in sorted(tr["min_clearance_mm_by_obstacle"].items(), key=lambda kv: kv[1]["mm"]):
            L.append(f"| {k} | {v['mm']} | {v['where']} |")
        L.append("")
        L.append("Waypoints: " + ", ".join(f"{w['name']} err {w['err_mm']} mm / tilt {w['tilt_deg']} deg" for w in tr["waypoints"]))
    s = rep["starter"]
    L += ["", "## Starter - vacuum picker on a Y/Z rail", "",
          f"Y travel {s['y_travel_mm']} mm, Z stroke {s['z_stroke_mm']} mm. Flat pad: "
          f"{sum(r['reached_flat_pad'] for r in s['rows'])}/18 positions (only the box centre line). With a centering nest pad "
          f"(dished liner; the box floor stays flat): {sum(r['reached_with_centering_pad'] for r in s['rows'])}/18.", "",
          "| clearance | mm |", "|---|---:|"] + [f"| {k} | {v} |" for k, v in s["clearances_mm"].items()]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    which = sys.argv[1:] or ["starter", "plus", "pro", "md"]
    path = os.path.join(ROOT, "reports", "CT_COOP_A_showcase_reach.json")
    rep = json.load(open(path)) if os.path.exists(path) else {}
    t = time.time()
    for cfg in which:
        if cfg == "starter":
            rep["starter"] = starter_option()
        elif cfg in ("plus", "pro"):
            rep.setdefault(cfg, {})["eggs"] = so101_option(cfg)      # keep an existing "traj" (was dropped -> KeyError in md)
        elif cfg in ("plus_traj", "pro_traj"):
            c = cfg.split("_")[0]
            rep.setdefault(c, {})["traj"] = so101_traj(c)
        print(cfg, round(time.time() - t, 1), flush=True)
    json.dump(rep, open(path, "w"), indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o))
    if "md" in which:
        open(os.path.join(ROOT, "reports", "CT_COOP_A_showcase_reach.md"), "w").write(md(rep))
